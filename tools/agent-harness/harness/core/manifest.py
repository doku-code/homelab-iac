"""Managed-file manifest: the ownership model behind safe updates.

Every file the harness installs into a consumer repository is recorded in
``.harness/manifest.json`` together with the SHA-256 of the content *as
installed*. On update, the harness can therefore distinguish:

* unchanged managed file  → safe to replace with the new upstream version
* locally modified file   → conflict; never overwritten silently
* project-owned file      → never touched (milestones, tasks, docs, ...)

Files with *managed blocks* (AGENTS.md, CLAUDE.md, .gitignore) are recorded
with the hash of the block only, so edits outside the block are never
conflicts.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from pathlib import Path

from harness.core.config import MANIFEST_FILENAME, STATE_DIR
from harness.core.util import sha256_text, write_text

# Ownership kinds
MANAGED = "managed"        # whole file owned by the harness (replaced on update if unmodified)
BLOCK = "block"            # harness owns a marked block inside a project file
GENERATED = "generated"    # regenerated by harness commands; never edited by hand
SEED = "seed"              # created once by init; project-owned afterwards; never updated


@dataclass
class Entry:
    path: str
    kind: str
    hash: str
    version: str
    template: str | None = None


@dataclass
class Manifest:
    harness_version: str
    entries: dict[str, Entry] = field(default_factory=dict)

    def record(self, path: str, kind: str, content: str, version: str, template: str | None = None) -> None:
        self.entries[path] = Entry(path=path, kind=kind, hash=sha256_text(content), version=version, template=template)

    def get(self, path: str) -> Entry | None:
        return self.entries.get(path)

    def to_json(self) -> str:
        data = {
            "harness_version": self.harness_version,
            "entries": [asdict(e) for e in sorted(self.entries.values(), key=lambda e: e.path)],
        }
        return json.dumps(data, indent=2, sort_keys=False) + "\n"


def manifest_path(root: Path) -> Path:
    return root / STATE_DIR / MANIFEST_FILENAME


def load(root: Path) -> Manifest | None:
    p = manifest_path(root)
    if not p.exists():
        return None
    data = json.loads(p.read_text(encoding="utf-8"))
    m = Manifest(harness_version=data.get("harness_version", "0.0.0"))
    for e in data.get("entries", []):
        m.entries[e["path"]] = Entry(**e)
    return m


def save(root: Path, manifest: Manifest) -> bool:
    return write_text(manifest_path(root), manifest.to_json())
