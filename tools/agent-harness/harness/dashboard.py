"""Generated project dashboard (`harness docs index` → ``<docs>/dashboard.md``).

One Markdown page that answers "where are we?" at a glance: milestone progress
bars, a Mermaid Gantt timeline, a task board grouped by status, recent commits,
verification commands and everything that needs attention. Like the knowledge
map it is derived purely from frontmatter, harness.yaml and the Git log, and it
contains no timestamps, so regenerating it on an unchanged repository is a
no-op and staleness can be detected by comparison.
"""

from __future__ import annotations

import datetime as dt
import posixpath
from collections import defaultdict

from harness.core.config import Config
from harness.core.documents import Catalog, Document, build_catalog
from harness.core.util import write_text
from harness.status import collect

DASHBOARD_NAME = "dashboard.md"
BOARD_ORDER = ["in-progress", "blocked", "planned", "completed", "cancelled"]
CLOSED_LIMIT = 15
PRIORITY_RANK = {"critical": 0, "high": 1, "medium": 2, "low": 3}
MERMAID_TAG = {"completed": "done", "active": "active", "blocked": "crit"}
BAR_CELLS = 10


def _meta_str(d: Document, key: str) -> str:
    v = d.meta.get(key)
    return "" if v is None else str(v)


def _date(value) -> dt.date | None:
    """Frontmatter dates arrive as ``datetime.date`` (YAML) or as strings; accept both."""
    if isinstance(value, dt.datetime):
        return value.date()
    if isinstance(value, dt.date):
        return value
    try:
        return dt.date.fromisoformat(str(value)[:10])
    except (TypeError, ValueError):
        return None


def _link(doc: Document, from_dir: str) -> str:
    target = posixpath.relpath(doc.relpath, from_dir) if from_dir else doc.relpath
    return f"[{doc.title}]({target})"


def _progress(tasks: list[Document]) -> str:
    counted = [t for t in tasks if t.status != "cancelled"]
    done = sum(1 for t in counted if t.status == "completed")
    total = len(counted)
    filled = (BAR_CELLS * done) // total if total else 0
    return "█" * filled + "░" * (BAR_CELLS - filled) + f" {done}/{total}"


def _gantt_line(m: Document) -> str | None:
    start = _date(m.meta.get("created"))
    if start is None:
        return None
    end = _date(m.meta.get("updated"))
    if end is None or end <= start:
        end = start + dt.timedelta(days=1)
    label = f"{m.id} {m.title}".replace(":", "").replace("#", "")[:40].rstrip()
    parts = [MERMAID_TAG[m.status]] if m.status in MERMAID_TAG else []
    parts += [m.id.lower(), start.isoformat(), end.isoformat()]
    return f"    {label} :{', '.join(parts)}"


def _board_sort(status: str, tasks: list[Document]) -> list[Document]:
    if status in ("completed", "cancelled"):
        return sorted(tasks, key=lambda t: (_meta_str(t, "updated"), t.id), reverse=True)
    return sorted(tasks, key=lambda t: (PRIORITY_RANK.get(_meta_str(t, "priority"), 4), t.id))


def render_dashboard(config: Config, catalog: Catalog | None = None, *, recent: int = 10) -> str:
    """Render the dashboard Markdown. Deterministic for an unchanged repository."""
    catalog = catalog or build_catalog(config)
    data = collect(config, catalog, recent=recent)
    from_dir = posixpath.dirname(f"{config.get('paths.docs')}/{DASHBOARD_NAME}")
    milestones = sorted(catalog.of_type("milestone"), key=lambda d: d.id)
    tasks = catalog.of_type("task")
    by_milestone: dict[str, list[Document]] = defaultdict(list)
    by_status: dict[str, list[Document]] = defaultdict(list)
    for t in tasks:
        by_milestone[_meta_str(t, "milestone")].append(t)
        by_status[t.status or "?"].append(t)

    out: list[str] = [
        "---", "id: INDEX-dashboard", "title: Dashboard", "type: index", "status: generated", "generated: true",
        "generator: harness docs index", "tags: [index, dashboard]", "---", "", "# Dashboard", "",
        "Generated by `harness docs index`. Do not edit; regenerate instead.", "",
    ]

    out += ["## Milestones", ""]
    if milestones:
        out += ["| ID | Status | Priority | Title | Progress |", "|----|--------|----------|-------|----------|"]
        for m in milestones:
            out.append(f"| {m.id} | {m.status} | {_meta_str(m, 'priority')} | {_link(m, from_dir)} | "
                       f"{_progress(by_milestone.get(m.id, []))} |")
    else:
        out.append("_No milestones._")
    out.append("")

    gantt = [line for line in (_gantt_line(m) for m in milestones) if line]
    if gantt:
        out += ["## Timeline", "", "```mermaid", "gantt", "    dateFormat YYYY-MM-DD", "    title Milestones",
                *gantt, "```", ""]

    out += ["## Task board", ""]
    if tasks:
        for status in BOARD_ORDER:
            rows = _board_sort(status, by_status.get(status, []))
            if not rows:
                continue
            shown = rows[:CLOSED_LIMIT] if status in ("completed", "cancelled") else rows
            out += [f"### {status}", "", "| ID | Priority | Milestone | Title |", "|----|----------|-----------|-------|"]
            for t in shown:
                out.append(f"| {t.id} | {_meta_str(t, 'priority')} | {_meta_str(t, 'milestone')} | "
                           f"{_link(t, from_dir)} |")
            if len(rows) > len(shown):
                out.append(f"… and {len(rows) - len(shown)} more")
            out.append("")
    else:
        out += ["_No tasks._", ""]

    # No "recent commits" section: it would change on every commit and make the committed dashboard churn.
    # Git log and the history records already cover that; CI exports a fresh copy to the wiki.
    out += ["## Verification", ""]
    if data["verification_commands"]:
        for c in data["verification_commands"]:
            flag = "" if c.get("verified") else " (not yet verified)"
            out.append(f"- `{c.get('run')}` — {c.get('name', 'run')}{flag}")
    else:
        out.append("_None configured._")
    out.append("")

    out += ["## Needs attention", ""]
    attention = [f"- {r['id']} — {r['path']}" for r in data["needs_revalidation"]]
    attention += [f"- {t['id']} — {t['title']}" for t in data["blocked_tasks"]]
    attention += [f"- {m['id']} — {m['title']}" for m in data["blocked_milestones"]]
    # Stale-index state is transient and belongs to `harness check`; embedding it made the dashboard rewrite itself.
    out += attention or ["_Nothing._"]
    out.append("")
    return "\n".join(out)


def write_dashboard(config: Config, catalog: Catalog | None = None) -> bool:
    """Write ``<docs>/dashboard.md``; return True when the file was created or changed."""
    return write_text(config.rel_path("docs") / DASHBOARD_NAME, render_dashboard(config, catalog))
